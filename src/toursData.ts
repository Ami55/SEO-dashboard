// Generate 365 days of realistic daily time series data
export function generateDailyTimeSeries(): GscDailyTimeSeriesPoint[] {
  const points: GscDailyTimeSeriesPoint[] = [];
  const baseDate = new Date('2026-08-17'); // Latest complete date
  
  for (let i = 364; i >= 0; i--) {
    const d = new Date(baseDate);
    d.setDate(d.getDate() - i);
    const dateStr = d.toISOString().split('T')[0];

    const prevD = new Date(d);
    prevD.setDate(prevD.getDate() - 364);
    const prevDateStr = prevD.toISOString().split('T')[0];

    const dayOfWeek = d.getDay(); // 0 = Sun, 6 = Sat
    const isWeekend = dayOfWeek === 0 || dayOfWeek === 6;
    
    // Base seasonal multiplier (peaks in May - August for summer travel)
    const month = d.getMonth(); // 0-11
    const seasonMultiplier = month >= 4 && month <= 7 ? 1.35 : month >= 2 && month <= 3 ? 1.15 : 0.88;
    const weekendMultiplier = isWeekend ? 1.18 : 0.96;
    const dayProgress = (365 - i) / 365;
    const growthTrend = 1.0 + (dayProgress * 0.22); // 22% annualized growth

    // Daily variations
    const noise = 0.94 + Math.sin(i * 0.4) * 0.05 + Math.cos(i * 0.15) * 0.04;
    
    const dailyClicks = Math.round(1620 * seasonMultiplier * weekendMultiplier * growthTrend * noise);
    const dailyImpressions = Math.round(dailyClicks * (60 + Math.sin(i * 0.2) * 8));
    const dailyCtr = Number((dailyClicks / dailyImpressions).toFixed(4));
    const dailyPosition = Number((8.8 - dayProgress * 0.8 + (Math.sin(i * 0.3) * 0.25)).toFixed(1));

    // Previous year corresponding day
    const prevNoise = 0.93 + Math.sin((i + 30) * 0.4) * 0.05;
    const prevClicks = Math.round(1310 * seasonMultiplier * weekendMultiplier * prevNoise);
    const prevImpressions = Math.round(prevClicks * 64);
    const prevCtr = Number((prevClicks / prevImpressions).toFixed(4));
    const prevPosition = Number((9.9 - (dayProgress * 0.5) + (Math.cos(i * 0.3) * 0.3)).toFixed(1));

    const options: Intl.DateTimeFormatOptions = { month: 'short', day: 'numeric' };
    const formattedDate = d.toLocaleDateString('en-US', options);
    const prevFormattedDate = prevD.toLocaleDateString('en-US', options);

    points.push({
      date: dateStr,
      formattedDate,
      clicks: dailyClicks,
      impressions: dailyImpressions,
      ctr: dailyCtr,
      position: dailyPosition,
      prevDate: prevDateStr,
      prevFormattedDate,
      prevClicks,
      prevImpressions,
      prevCtr,
      prevPosition,
      byPageGroup: {
        'City or Area Pages': { clicks: Math.round(dailyClicks * 0.38), impressions: Math.round(dailyImpressions * 0.36) },
        'Shore Excursions': { clicks: Math.round(dailyClicks * 0.22), impressions: Math.round(dailyImpressions * 0.20) },
        'Tour Guides': { clicks: Math.round(dailyClicks * 0.15), impressions: Math.round(dailyImpressions * 0.14) },
        'Tour Detail Pages': { clicks: Math.round(dailyClicks * 0.12), impressions: Math.round(dailyImpressions * 0.13) },
        'Travel Blog': { clicks: Math.round(dailyClicks * 0.08), impressions: Math.round(dailyImpressions * 0.11) },
        'Cruise Lines': { clicks: Math.round(dailyClicks * 0.03), impressions: Math.round(dailyImpressions * 0.04) },
        'Safaris': { clicks: Math.round(dailyClicks * 0.02), impressions: Math.round(dailyImpressions * 0.02) },
      },
      brandedClicks: Math.round(dailyClicks * 0.24),
      nonBrandedClicks: Math.round(dailyClicks * 0.76),
      desktopClicks: Math.round(dailyClicks * 0.58),
      mobileClicks: Math.round(dailyClicks * 0.38),
      tabletClicks: Math.round(dailyClicks * 0.04),
    });
  }

  return points;
}

