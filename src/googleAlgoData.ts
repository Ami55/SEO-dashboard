export const GOOGLE_ALGORITHM_UPDATES = OFFICIAL_GOOGLE_ALGORITHM_UPDATES;

const STORAGE_KEY = 'semantic_mapper_google_algo_updates_v2';

/**
 * Load algorithm updates from localStorage merged with official defaults
 */
export function getSavedAlgorithmUpdates(): GoogleAlgorithmUpdateEvent[] {
  if (typeof window === 'undefined') {
    return OFFICIAL_GOOGLE_ALGORITHM_UPDATES;
  }
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) {
      return OFFICIAL_GOOGLE_ALGORITHM_UPDATES;
    }
    const parsed: GoogleAlgorithmUpdateEvent[] = JSON.parse(raw);
    if (Array.isArray(parsed) && parsed.length > 0) {
      const officialIds = new Set(OFFICIAL_GOOGLE_ALGORITHM_UPDATES.map((u) => u.id));
      const customOnes = parsed.filter((p) => !officialIds.has(p.id));
      return [...customOnes, ...OFFICIAL_GOOGLE_ALGORITHM_UPDATES];
    }
  } catch (e) {
    console.error('Failed to parse algorithm updates from storage', e);
  }
  return OFFICIAL_GOOGLE_ALGORITHM_UPDATES;
}

/**
 * Save updated list of algorithm events to localStorage
 */
export function saveAlgorithmUpdates(updates: GoogleAlgorithmUpdateEvent[]) {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(updates));
  } catch (e) {
    console.error('Failed to save algorithm updates to storage', e);
  }
}

/**
 * Reset algorithm events to official defaults
 */
export function resetAlgorithmUpdates(): GoogleAlgorithmUpdateEvent[] {
  if (typeof window !== 'undefined') {
    localStorage.removeItem(STORAGE_KEY);
  }
  return OFFICIAL_GOOGLE_ALGORITHM_UPDATES;
}
